import XCTest
@testable import MarkmeCore

final class ReaderCopyTests: XCTestCase {
    func testPortugueseAndEnglishCopy() {
        XCTAssertEqual(ReaderCopy.string(.modeSource, languageCode: "pt-BR"), "Texto")
        XCTAssertEqual(ReaderCopy.string(.modeSplit, languageCode: "pt"), "Lado a lado")
        XCTAssertEqual(ReaderCopy.string(.modePage, languageCode: "pt-BR"), "Página")
        XCTAssertEqual(ReaderCopy.string(.modePresentation, languageCode: "pt-BR"), "Apresentação")
        XCTAssertEqual(ReaderCopy.string(.modePresentation, languageCode: "en"), "Presentation")
        XCTAssertEqual(ReaderCopy.string(.bannerQuestion, languageCode: "pt-BR"), "Quer abrir os markdown neste visualizador?")
        XCTAssertEqual(ReaderCopy.string(.bannerAccept, languageCode: "pt-BR"), "Usar como padrão")
        XCTAssertEqual(ReaderCopy.string(.bannerNotNow, languageCode: "pt-BR"), "Agora não")
        XCTAssertEqual(ReaderCopy.string(.menuMakeDefault, languageCode: "pt-BR"), "Usar como leitor padrão de Markdown")
        XCTAssertEqual(ReaderCopy.string(.notUTF8, languageCode: "pt-BR"), "Este arquivo não está em texto UTF-8.")
        XCTAssertEqual(ReaderCopy.string(.unreadable, languageCode: "pt-BR"), "Não foi possível ler este arquivo.")
        XCTAssertEqual(ReaderCopy.string(.findPrompt, languageCode: "pt-BR"), "Buscar")
        XCTAssertEqual(ReaderCopy.string(.zoomIn, languageCode: "pt-BR"), "Aumentar")
        XCTAssertEqual(ReaderCopy.string(.zoomOut, languageCode: "pt-BR"), "Diminuir")
        XCTAssertEqual(ReaderCopy.string(.actualSize, languageCode: "pt-BR"), "Tamanho real")
        XCTAssertEqual(ReaderCopy.string(.zoomIn, languageCode: "en"), "Zoom In")
        XCTAssertEqual(ReaderCopy.string(.zoomOut, languageCode: "en"), "Zoom Out")
        XCTAssertEqual(ReaderCopy.string(.actualSize, languageCode: "en"), "Actual Size")
        XCTAssertEqual(ReaderCopy.string(.viewMenu, languageCode: "pt-BR"), "Visualizar")
        XCTAssertEqual(ReaderCopy.string(.viewMenu, languageCode: "en"), "View")
        XCTAssertEqual(ReaderCopy.string(.modeSource, languageCode: "en"), "Text")
        XCTAssertEqual(ReaderCopy.string(.modeSplit, languageCode: "fr"), "Side by side")
        XCTAssertEqual(ReaderCopy.string(.modePage, languageCode: "en"), "Page")
        XCTAssertEqual(ReaderCopy.string(.bannerQuestion, languageCode: "en"), "Open Markdown files in this viewer?")
        XCTAssertEqual(ReaderCopy.string(.notUTF8, languageCode: "en"), "This file is not UTF-8 text.")
        XCTAssertEqual(ReaderCopy.string(.unreadable, languageCode: "en"), "Could not read this file.")
        XCTAssertEqual(ReaderCopy.string(.changesSeen, languageCode: "pt-BR"), "Visto")
        XCTAssertEqual(ReaderCopy.string(.changesSeen, languageCode: "en"), "Seen")
        XCTAssertEqual(ReaderCopy.string(.changesPrevious, languageCode: "pt-BR"), "Mudança anterior")
        XCTAssertEqual(ReaderCopy.string(.changesNext, languageCode: "en"), "Next change")
        XCTAssertEqual(ReaderCopy.linesRemoved(1, languageCode: "pt-BR"), "1 linha removida")
        XCTAssertEqual(ReaderCopy.linesRemoved(3, languageCode: "pt"), "3 linhas removidas")
        XCTAssertEqual(ReaderCopy.linesRemoved(1, languageCode: "en"), "1 line removed")
        XCTAssertEqual(ReaderCopy.linesRemoved(4, languageCode: "en"), "4 lines removed")
        XCTAssertEqual(ReaderCopy.changePosition(current: 2, total: 5, languageCode: "pt-BR"), "2 de 5")
        XCTAssertEqual(ReaderCopy.changePosition(current: 2, total: 5, languageCode: "en"), "2 of 5")
        XCTAssertEqual(ReaderCopy.string(.copyLocation, languageCode: "pt-BR"), "Copiar localização")
        XCTAssertEqual(ReaderCopy.string(.copyLocation, languageCode: "en"), "Copy Location")
        XCTAssertEqual(ReaderCopy.string(.alertNote, languageCode: "pt-BR"), "Nota")
        XCTAssertEqual(ReaderCopy.string(.alertTip, languageCode: "pt"), "Dica")
        XCTAssertEqual(ReaderCopy.string(.alertImportant, languageCode: "pt-BR"), "Importante")
        XCTAssertEqual(ReaderCopy.string(.alertWarning, languageCode: "pt-BR"), "Aviso")
        XCTAssertEqual(ReaderCopy.string(.alertCaution, languageCode: "pt-BR"), "Cuidado")
        XCTAssertEqual(ReaderCopy.string(.alertNote, languageCode: "en"), "Note")
        XCTAssertEqual(ReaderCopy.string(.alertCaution, languageCode: "en"), "Caution")
        XCTAssertEqual(ReaderCopy.string(.featureGoals, languageCode: "pt-BR"), "Objetivos")
        XCTAssertEqual(ReaderCopy.string(.featureGoals, languageCode: "en"), "Goals")
        XCTAssertEqual(ReaderCopy.string(.featureNonGoals, languageCode: "pt"), "Fora")
        XCTAssertEqual(ReaderCopy.string(.featureNonGoals, languageCode: "en"), "Out of scope")
        XCTAssertEqual(ReaderCopy.string(.featureTasks, languageCode: "pt-BR"), "Tarefas")
        XCTAssertEqual(ReaderCopy.string(.featureTasks, languageCode: "en"), "Tasks")
        XCTAssertEqual(ReaderCopy.string(.featureSpec, languageCode: "pt-BR"), "Spec")
        XCTAssertEqual(ReaderCopy.string(.featurePlan, languageCode: "pt-BR"), "Plano")
        XCTAssertEqual(ReaderCopy.string(.featurePlan, languageCode: "en"), "Plan")
    }
}
